--
-- Rulare: Supabase Dashboard -> SQL Editor -> New query -> lipesti tot fisierul -> Run. O singura data
-- (e sigur si daca il rulezi din nou: nu sterge si nu dubleaza nimic). Trebuie rulat dupa supabase-deee-1-nomenclatoare-retete.sql.
-- Datele de pornire sunt cele din WiseWeee (85 echipamente, 144 coduri de organizatii, 506 legaturi); le poti edita din
-- aplicatie: tab-ul ♻️ DEEE -> Nomenclatoare.

alter table public.deee_echipamente add column if not exists greutate_medie numeric;
alter table public.deee_echipamente add column if not exists categorie text;
alter table public.deee_echipamente add column if not exists wise_id integer unique;

-- Categorii WEEELABEX cu tintele de reciclare / valorificare (procente).
create table if not exists public.deee_categorii (
  cat text primary key,
  created_at timestamptz not null default now(),
  denumire text not null,
  tinta_valorificare numeric not null default 0,
  tinta_reciclare numeric not null default 0
);

-- Coduri ale organizatiilor (ECOTIC, ECOPOSITIVE, REDPOINT, CNREE, ENVIRON, RLG).
create table if not exists public.deee_coduri_org (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  organizatie text not null,
  cod text not null,
  denumire text not null default '',
  categorie text not null default '',
  grupa text not null default '',
  wise_id integer unique
);
create index if not exists deee_coduri_org_org_idx on public.deee_coduri_org (organizatie);

-- Ce cod are fiecare echipament la fiecare organizatie ("implicit" = cel folosit in rapoarte si exporturi).
create table if not exists public.deee_echipament_cod (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  echipament_id uuid not null references public.deee_echipamente(id) on delete cascade,
  cod_id uuid not null references public.deee_coduri_org(id) on delete cascade,
  implicit boolean not null default false,
  unique (echipament_id, cod_id)
);
create index if not exists deee_echipament_cod_ech_idx on public.deee_echipament_cod (echipament_id);

do $$
declare t text;
begin
  foreach t in array array['deee_categorii','deee_coduri_org','deee_echipament_cod']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "acces_aplicatie" on public.%I', t);
    execute format('create policy "acces_aplicatie" on public.%I for all using (true) with check (true)', t);
  end loop;
end $$;

